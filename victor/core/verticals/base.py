def _lazy_toolset() -> Any:
    """Lazy factory for ToolSet default — avoids eager framework import."""
    from victor.framework.tools import ToolSet

    return ToolSet()


def _lazy_toolset_from_tools(tool_names: List[str]) -> Any:
    """Lazy ToolSet.from_tools() — avoids eager framework import."""
    from victor.framework.tools import ToolSet

    return ToolSet.from_tools(tool_names)


@dataclass
class VerticalConfig:
    """Configuration generated by a vertical.

    This is passed to Agent.create() to configure the agent.

    Attributes:
        tools: ToolSet configuration
        system_prompt: System prompt text
        stages: Stage definitions
        provider_hints: Hints for provider selection
        evaluation_criteria: Criteria for evaluating agent performance
        metadata: Additional vertical-specific metadata
    """

    name: str = ""
    description: str = ""
    tools: Any = field(default_factory=lambda: _lazy_toolset())
    system_prompt: str = ""
    stages: Dict[str, StageDefinition] = field(default_factory=dict)
    provider_hints: Dict[str, Any] = field(default_factory=dict)
    evaluation_criteria: List[str] = field(default_factory=list)
    metadata: Dict[str, Any] = field(default_factory=dict)
    tier: Tier = Tier.STANDARD
    extensions: Dict[str, Any] = field(default_factory=dict)

    def to_agent_kwargs(self) -> Dict[str, Any]:
        """Convert to kwargs for Agent.create().

        Returns:
            Dictionary of keyword arguments.
        """
        return {
            "tools": self.tools,
            # System prompt is typically handled separately
        }

    def to_dict(self) -> Dict[str, Any]:
        """Convert config to dictionary for dict-like access.

        Returns:
            Dictionary representation of the configuration.
        """
        return {
            "name": self.name,
            "description": self.description,
            "tools": self.get_tool_names(),
            "system_prompt": self.system_prompt,
            "stages": {
                k: {"name": v.name, "description": v.description} for k, v in self.stages.items()
            },
            "provider_hints": self.provider_hints,
            "evaluation_criteria": self.evaluation_criteria,
            "metadata": self.metadata,
            "tier": self.tier.value,
            "extensions": self.extensions,
        }

    def get_tool_names(self) -> List[str]:
        """Return tool names in SDK-compatible list form."""

        if not self.tools:
            return []
        return sorted(self.tools.get_tool_names())

    def get_stage_names(self) -> List[str]:
        """Return stage names in declaration order."""

        return list(self.stages.keys())

    def with_metadata(self, **kwargs: Any) -> "VerticalConfig":
        """Return a copy with additional metadata merged in."""

        return VerticalConfig(
            name=self.name,
            description=self.description,
            tools=self.tools,
            system_prompt=self.system_prompt,
            stages=self.stages,
            provider_hints=self.provider_hints,
            evaluation_criteria=self.evaluation_criteria,
            metadata={**self.metadata, **kwargs},
            tier=self.tier,
            extensions=self.extensions,
        )

    def with_extension(self, key: str, value: Any) -> "VerticalConfig":
        """Return a copy with one additional extension entry."""

        return VerticalConfig(
            name=self.name,
            description=self.description,
            tools=self.tools,
            system_prompt=self.system_prompt,
            stages=self.stages,
            provider_hints=self.provider_hints,
            evaluation_criteria=self.evaluation_criteria,
            metadata=self.metadata,
            tier=self.tier,
            extensions={**self.extensions, key: value},
        )

    def keys(self):
        """Return keys for dict-like access compatibility.

        Returns:
            Keys iterator for dictionary representation.
        """
        return self.to_dict().keys()

    def __getitem__(self, key: str) -> Any:
        """Enable dict-like access: config["key"].

        Args:
            key: Configuration key

        Returns:
            Configuration value

        Raises:
            KeyError: If key not found
        """
        d = self.to_dict()
        if key not in d:
            raise KeyError(key)
        return d[key]

    def get(self, key: str, default: Any = None) -> Any:
        """Get config value with default, like dict.get().

        Args:
            key: Configuration key
            default: Default value if key not found

        Returns:
            Configuration value or default
        """
        try:
            return self[key]
        except KeyError:
            return default


class VerticalBase(
    VerticalMetadataProvider,
    VerticalExtensionLoader,
    VerticalWorkflowProvider,
    SdkVerticalBase,  # Keep SDK contract in the hierarchy without shadowing runtime mixins
):
    """Abstract base class for domain-specific assistants.

    Implements the Template Method pattern using composition of focused
    capability providers for SRP compliance:

    - VerticalMetadataProvider: Metadata (name, description, version,
      provider_hints, evaluation_criteria, capability_configs)
    - VerticalExtensionLoader: Extension loading (middleware, safety,
      prompt_contributor, mode_config, tool_deps, etc.)
    - VerticalWorkflowProvider: Workflow and handler providers

    Subclasses must override:
    - name: Vertical identifier
    - description: Human-readable description
    - get_tools(): List of tool names
    - get_system_prompt(): System prompt text

    Optional overrides:
    - get_stages(): Stage definitions
    - customize_config(): Hook for final config customization
    - Extension methods: get_middleware(), get_safety_extension(), etc.

    Example:
        class SecurityAuditor(VerticalBase):
            name = "security_auditor"
            description = "Security vulnerability analysis"

            @classmethod
            def get_tools(cls):
                return ["read", "search", "security_scan"]

            @classmethod
            def get_system_prompt(cls):
                return "You are a security expert..."

    Config Caching:
        The get_config() method caches its result per-class to avoid
        repeated computation. Call clear_config_cache() to invalidate
        when config sources change (typically only needed in tests).

    Extension Loading:
        The get_extensions() method supports strict error handling.
        Set strict_extension_loading=True to raise ExtensionLoadError on
        any failure. Set required_extensions to specify which extensions
        must load successfully even in non-strict mode.

    Backward Compatibility:
        All methods from the original VerticalBase are preserved through
        inheritance from the focused provider classes. Existing verticals
        that inherit from VerticalBase require no changes.
    """

    VERTICAL_API_VERSION: ClassVar[int] = 1

    # Config cache (keyed by namespaced class identity, stores VerticalConfig)
    _config_cache: Dict[str, "VerticalConfig"] = {}
    _config_cache_lock: ClassVar[threading.RLock] = threading.RLock()
    _config_cache_timestamps: Dict[str, float] = {}
    _config_cache_ttl: ClassVar[float] = 300.0  # 5 min default, verticals can override

    @classmethod
    def _config_cache_key(cls) -> str:
        """Get namespaced cache key for this class."""
        return f"{cls.__name__}:{cls.__module__}:{cls.__qualname__}"

    # =========================================================================
    # Composition API (Phase 4 - SOLID Refactoring)
    # =========================================================================

    @classmethod
    def compose(cls) -> "CapabilityComposer":
        """Create a composer for this vertical.

        Provides a fluent builder API for composing vertical capabilities
        declaratively instead of using inheritance.

        Example:
            from victor.core.verticals.base import VerticalBase

            MyVertical = (
                VerticalBase
                .compose()
                .with_metadata("my_vertical", "My assistant", "1.0.0")
                .with_stages(custom_stages)
                .with_extensions([SafetyExtension(), LoggingExtension()])
                .build()
            )

        Returns:
            CapabilityComposer for building this vertical

        Note:
            This is an alternative to inheritance-based verticals.
            When feature flag USE_COMPOSITION_OVER_INHERITANCE is enabled,
            composition-based verticals will be used preferentially.
        """
        from victor.core.feature_flags import get_feature_flag_manager, FeatureFlag
        from victor.core.verticals.composition import CapabilityComposer

        # Check if composition mode is enabled
        if get_feature_flag_manager().is_enabled(FeatureFlag.USE_COMPOSITION_OVER_INHERITANCE):
            logger.debug(f"[{cls.__name__}] Using composition mode")

        return CapabilityComposer(cls)

    @classmethod
    def get_composer(cls) -> Optional["CapabilityComposer"]:
        """Get the composer if using composition mode.

        Returns:
            CapabilityComposer if this vertical was built via composition,
            None otherwise
        """
        return getattr(cls, "_composer", None)

    # =========================================================================
    # Required Abstract Methods
    # =========================================================================

    @classmethod
    @abstractmethod
    def get_tools(cls) -> List[str]:
        """Get the list of tool names for this vertical.

        Returns:
            List of tool names to enable.
        """
        pass

    @classmethod
    @abstractmethod
    def get_system_prompt(cls) -> str:
        """Get the system prompt for this vertical.

        Verticals can optionally append framework grounding rules by calling
        get_framework_grounding_rules() and appending to their prompt:

            prompt = "You are an expert in X..."
            prompt += "\\n\\n" + cls.get_framework_grounding_rules()
            return prompt

        Returns:
            System prompt text with domain expertise.
        """
        pass

    # =========================================================================
    # SDK Protocol Implementation (Dependency Inversion)
    # =========================================================================

    @classmethod
    def get_name(cls) -> str:
        """Return vertical identifier (SDK protocol implementation).

        Returns:
            Vertical name from class attribute.
        """
        return cls.name

    @classmethod
    def get_description(cls) -> str:
        """Return vertical description (SDK protocol implementation).

        Returns:
            Vertical description from class attribute.
        """
        return cls.description

    @classmethod
    def _get_toolset(cls) -> Any:
        """Convert tool names to ToolSet (SDK protocol implementation).

        This implements the SDK's abstract method by creating a ToolSet
        from the tool names returned by get_tools().

        Returns:
            ToolSet object with tools from get_tools().
        """
        tool_names = cls.get_tools()
        return _lazy_toolset_from_tools(tool_names)

    # =========================================================================
    # Framework Capability Helpers (Phase 1)
    # =========================================================================

    @classmethod
    def _get_stage_capability(cls) -> Any:
        """Get or create the stage builder capability (lazy-loaded)."""
        global _stage_capability
        if _stage_capability is None:
            from victor.framework.capabilities import StageBuilderCapability

            _stage_capability = StageBuilderCapability()
        return _stage_capability

    @classmethod
    def _get_grounding_capability(cls) -> Any:
        """Get or create the grounding rules capability (lazy-loaded)."""
        global _grounding_capability
        if _grounding_capability is None:
            from victor.framework.capabilities import GroundingRulesCapability

            _grounding_capability = GroundingRulesCapability()
        return _grounding_capability

    @classmethod
    def get_framework_stages(cls) -> Dict[str, Any]:
        """Get stage definitions from framework capability.

        This provides a way for verticals to access the generic 7-stage
        workflow template from the framework while allowing customization.

        Returns:
            Dictionary mapping stage names to stage definitions
        """
        capability = cls._get_stage_capability()
        return capability.get_stages()

    @classmethod
    def get_framework_grounding_rules(cls) -> str:
        """Get grounding rules text from framework capability.

        This provides a way for verticals to access the generic grounding
        rules from the framework while allowing extensions.

        Returns:
            Formatted grounding rules text
        """
        capability = cls._get_grounding_capability()
        return capability.get_rules_text(vertical=cls.name, include_extensions=True)

    # =========================================================================
    # Configurable Override Points
    # =========================================================================

    @classmethod
    def get_stages(cls) -> Dict[str, StageDefinition]:
        """Get stage definitions for this vertical.

        Default implementation uses the framework StageBuilderCapability
        to provide a comprehensive 7-stage workflow representing a generic
        problem-solving lifecycle. This promotes code reuse across verticals
        while allowing customization.

        Phase 2: Stage contract validation is applied to ensure LSP compliance.

        The 7-stage workflow template:
        1. INITIAL: Understand the request and gather initial context
        2. PLANNING: Design the approach and strategy
        3. READING: Gather detailed information and context
        4. ANALYSIS: Analyze information and identify solutions
        5. EXECUTION: Implement the planned changes
        6. VERIFICATION: Validate results and test outcomes
        7. COMPLETION: Finalize, document, and wrap up

        This workflow applies to most domains:
        - Coding: understand -> plan -> read code -> analyze -> implement -> test -> commit
        - DevOps: assess -> plan -> implement -> validate -> deploy -> monitor
        - Research: question -> search -> read -> synthesize -> write -> verify
        - Data Analysis: understand -> explore -> analyze -> visualize -> report

        Verticals can override this method to provide domain-specific:
        - Stage names (e.g., DEPLOYMENT, SYNTHESIZING)
        - Tools appropriate for each stage
        - Domain-specific keywords

        Returns:
            Dictionary mapping stage names to StageDefinition objects.
            Each stage includes description, keywords, and valid transitions.

        Raises:
            ValueError: If stage definitions fail contract validation.
        """
        # Use framework StageBuilderCapability for consistent default stages
        framework_stages = cls.get_framework_stages()

        # Convert framework stage dicts to StageDefinition objects
        # This maintains backward compatibility while using framework capabilities
        from victor.core.vertical_types import normalize_stage_definition

        stages = {}
        for stage_name, stage_def in framework_stages.items():
            stages[stage_name] = normalize_stage_definition(stage_name, stage_def)

        # Validate stages against contract (Phase 2: LSP compliance)
        # Use validator directly since VerticalBase is abstract
        try:
            # Convert to dict format for validation
            stages_dict = {
                name: {
                    "name": stage.name,
                    "description": stage.description,
                    "keywords": stage.keywords,
                    "next_stages": stage.next_stages,
                }
                for name, stage in stages.items()
            }
            result = validate_stage_contract(stages_dict, f"{cls.name}_stages")
            # Log warnings but don't fail on them
            for warning in result.warnings:
                logger.warning(f"[{cls.name}] Stage validation warning: {warning}")
        except Exception as e:
            # Don't fail on validation errors for backward compatibility
            logger.warning(f"[{cls.name}] Stage validation skipped: {e}")

        return stages

    @classmethod
    def get_skills(cls) -> List[Any]:
        """Return skill definitions for this vertical.

        Subclasses override this to declare composable skills. Each skill
        binds a prompt fragment with a tool subset and constraints.

        Returns:
            List of SkillDefinition objects (empty by default)
        """
        return []

    @classmethod
    def customize_config(cls, config: VerticalConfig) -> VerticalConfig:
        """Hook for final configuration customization.

        Override to modify the config before it's returned.

        Args:
            config: Configuration to customize.

        Returns:
            Customized configuration.
        """
        return config

    # =========================================================================
    # Template Method Implementation
    # =========================================================================

    @classmethod
    def get_config(cls, *, use_cache: bool = True) -> VerticalConfig:
        """Get the complete configuration for this vertical.

        This is the main template method that assembles the configuration
        by calling the various override points.

        Args:
            use_cache: If True (default), return cached config if available.
                       Set to False to force rebuild.

        Returns:
            Complete VerticalConfig for agent creation.
        """
        cache_key = cls._config_cache_key()

        # Return cached config if available and caching enabled
        if use_cache:
            with cls._config_cache_lock:
                cached = cls._config_cache.get(cache_key)
                if cached is not None:
                    ts = cls._config_cache_timestamps.get(cache_key, 0.0)
                    if time.time() - ts < cls._config_cache_ttl:
                        return cached
                    # Expired — remove stale entry and fall through to rebuild
                    cls._config_cache.pop(cache_key, None)
                    cls._config_cache_timestamps.pop(cache_key, None)

        # Build tool set — with crash containment for each hook
        try:
            tool_names = cls.get_tools()
            tools = _lazy_toolset_from_tools(tool_names)
        except Exception as e:
            logger.warning("Vertical %s: get_tools() failed: %s", cls.name, e)
            tools = _lazy_toolset()

        try:
            system_prompt = cls.get_system_prompt()
        except Exception as e:
            logger.warning("Vertical %s: get_system_prompt() failed: %s", cls.name, e)
            system_prompt = ""

        try:
            stages = cls.get_stages()
        except Exception as e:
            logger.warning("Vertical %s: get_stages() failed: %s", cls.name, e)
            stages = {}

        try:
            provider_hints = cls.get_provider_hints()
        except Exception as e:
            logger.warning("Vertical %s: get_provider_hints() failed: %s", cls.name, e)
            provider_hints = {}

        try:
            evaluation_criteria = cls.get_evaluation_criteria()
        except Exception as e:
            logger.warning("Vertical %s: get_evaluation_criteria() failed: %s", cls.name, e)
            evaluation_criteria = []

        # Build config
        config = VerticalConfig(
            name=cls.name,
            description=cls.description,
            tools=tools,
            system_prompt=system_prompt,
            stages=stages,
            provider_hints=provider_hints,
            evaluation_criteria=evaluation_criteria,
            metadata={
                "vertical_name": cls.name,
                "vertical_version": cls.version,
                "description": cls.description,
            },
        )

        # Allow final customization
        config = cls.customize_config(config)

        # Cache the config
        with cls._config_cache_lock:
            cls._config_cache[cache_key] = config
            cls._config_cache_timestamps[cache_key] = time.time()
        return config

    @classmethod
    def clear_config_cache(cls, *, clear_all: bool = False) -> None:
        """Clear the config cache for this vertical.

        Also clears individual extension cache entries created by
        _get_cached_extension() for this class.

        Args:
            clear_all: If True, clear cache for all verticals.
                       If False (default), clear only for this class.
        """
        if clear_all:
            with cls._config_cache_lock:
                cls._config_cache.clear()
                cls._config_cache_timestamps.clear()
            cls.clear_extension_cache(clear_all=True)
        else:
            cache_key = cls._config_cache_key()
            with cls._config_cache_lock:
                cls._config_cache.pop(cache_key, None)
                cls._config_cache_timestamps.pop(cache_key, None)
                # Backward compatibility for legacy class-name cache keys.
                cls._config_cache.pop(cls.__name__, None)
            # Clear extensions cache for this class too
            cls.clear_extension_cache(clear_all=False)

    # Class-level LSP capability storage
    _lsp_capability: ClassVar[Optional[Any]] = None

    @classmethod
    def get_lsp(cls) -> Optional[Any]:
        """Get the LSP capability for this vertical.

        Returns:
            LSPCapability instance or None
        """
        return cls._lsp_capability

    @classmethod
    def set_lsp(cls, lsp_capability: Any) -> None:
        """Set the LSP capability for this vertical.

        Enables language intelligence features for this vertical.

        Args:
            lsp_capability: LSPCapability instance
        """
        cls._lsp_capability = lsp_capability

    @classmethod
    def register_tools(cls, registry: Any) -> None:
        """Hook for verticals to register custom tools during activation.

        Override this method to register vertical-specific tools with the
        tool registry or orchestrator when the vertical is activated.

        Args:
            registry: Tool registry or orchestrator to register tools with.
        """
        pass

    @classmethod
    def get_tool_set(cls) -> Any:
        """Get the ToolSet for this vertical.

        Convenience method that returns just the tool configuration.

        Returns:
            Configured ToolSet.
        """
        return _lazy_toolset_from_tools(cls.get_tools())

    @classmethod
    async def create_agent(
        cls,
        provider: str = "anthropic",
        model: Optional[str] = None,
        **kwargs: Any,
    ) -> Any:
        """Factory method to create an agent with this vertical's config.

        Args:
            provider: LLM provider name.
            model: Optional model identifier.
            **kwargs: Additional arguments passed to Agent.create().

        Returns:
            Configured Agent instance.
        """
        raise NotImplementedError(
            "VerticalBase.create_agent() has been removed. "
            "Use Agent.create(vertical=YourVertical) instead."
        )


class VerticalRegistry:
    """Registry for discovering and accessing verticals.

    Implements the Registry pattern for vertical discovery.

    Supports both built-in verticals and externally registered verticals.
    The canonical external packaging path is ``victor.plugins``, where a
    ``VictorPlugin`` registers one or more vertical classes with the host.
    ``victor.verticals`` remains as a legacy compatibility discovery path.

    Example:
        # Runtime registration path used by VictorPlugin/plugin bootstrap
        VerticalRegistry.register(MyVertical)

        # List available verticals
        for name, vertical in VerticalRegistry.list_all():
            print(f"{name}: {vertical.description}")

        # Get a specific vertical
        coding = VerticalRegistry.get("coding")

    Canonical External Packaging Format:
        # In external package's pyproject.toml
        [project.entry-points."victor.plugins"]
        security = "victor_security:plugin"

    Legacy Entry Point Format (compatibility only):
        [project.entry-points."victor.verticals"]
        security = "victor_security:SecurityAssistant"
    """

    _registry: Dict[str, Type[VerticalBase]] = {}
    _provenance: Dict[str, str] = {}
    _external_discovered: bool = False
    _legacy_entry_point_warning_emitted: bool = False
    ENTRY_POINT_GROUP: str = "victor.plugins"  # Consolidated from legacy "victor.verticals"
    MINIMUM_SUPPORTED_API_VERSION: ClassVar[int] = SDK_MIN_SUPPORTED_API_VERSION
    CURRENT_API_VERSION: ClassVar[int] = SDK_CURRENT_API_VERSION

    @classmethod
    def _is_contrib_vertical(cls, vertical: Type[VerticalBase]) -> bool:
        """Return True when *vertical* is marked as a contrib vertical."""

        return get_vertical_runtime_provenance(vertical) is VerticalRuntimeProvenance.CONTRIB

    @classmethod
    def register(cls, vertical: Type[VerticalBase]) -> None:
        """Register a vertical with external-over-contrib priority.

        Priority rules:
        - External packages always take priority over built-in contrib verticals.
        - If an external vertical is already registered and a contrib version
          tries to register, the contrib is silently skipped.
        - If a contrib vertical is already registered and an external version
          registers, the external quietly overrides it.

        Args:
            vertical: Vertical class to register.

        Raises:
            ValueError: If vertical has no name.
        """
        import logging

        logger = logging.getLogger(__name__)

        manifest = get_or_create_vertical_manifest(vertical)
        if manifest is None:
            raise ValueError(
                f"Vertical {vertical.__name__} does not expose a valid ExtensionManifest"
            )

        name = manifest.name or getattr(vertical, "name", "")
        if not name:
            raise ValueError(f"Vertical {vertical.__name__} has no name defined")

        vertical.name = name
        new_module = getattr(vertical, "__module__", "<unknown>")

        if name in cls._registry:
            existing = cls._registry[name]
            existing_module = getattr(existing, "__module__", "<unknown>")
            if existing is not vertical:
                existing_is_contrib = cls._is_contrib_vertical(existing)
                new_is_contrib = cls._is_contrib_vertical(vertical)

                if not existing_is_contrib and new_is_contrib:
                    # External already registered; contrib trying to overwrite — skip
                    logger.debug(
                        "Skipping contrib vertical '%s' (%s) — external version "
                        "already registered from %s.",
                        name,
                        new_module,
                        existing_module,
                    )
                    return
                elif existing_is_contrib and not new_is_contrib:
                    # External overriding contrib — expected upgrade
                    logger.info(
                        "External vertical '%s' (%s) overrides deprecated " "contrib version (%s).",
                        name,
                        new_module,
                        existing_module,
                    )
                else:
                    # Genuine collision (both external or both contrib)
                    logger.warning(
                        "Vertical name collision: '%s' already registered by %s "
                        "(module: %s). Overwriting with %s (module: %s).",
                        name,
                        existing.__name__,
                        existing_module,
                        vertical.__name__,
                        new_module,
                    )

        cls._registry[name] = vertical
        cls._provenance[name] = new_module

    @classmethod
    def unregister(cls, name: str) -> None:
        """Unregister a vertical.

        Args:
            name: Vertical name to unregister.
        """
        if name in cls._registry:
            del cls._registry[name]

    @classmethod
    def get(cls, name: str) -> Optional[Type[VerticalBase]]:
        """Get a vertical by name.

        Args:
            name: Vertical name.

        Returns:
            Vertical class or None if not found.
        """
        return cls._registry.get(name)

    @classmethod
    def list_all(cls) -> List[tuple[str, Type[VerticalBase]]]:
        """List all registered verticals.

        Returns:
            List of (name, vertical_class) tuples.
        """
        return list(cls._registry.items())

    @classmethod
    def list_names(cls) -> List[str]:
        """List all registered vertical names.

        Returns:
            List of vertical names.
        """
        return list(cls._registry.keys())

    @classmethod
    def clear(cls, *, reregister_builtins: bool = True) -> None:
        """Clear all registered verticals (for testing).

        Args:
            reregister_builtins: If True (default), re-register built-in verticals
                after clearing. This prevents test pollution where clearing in one
                test affects other tests that expect built-ins to be available.
        """
        cls._registry.clear()
        cls._provenance.clear()
        cls._external_discovered = False
        cls._legacy_entry_point_warning_emitted = False

        if reregister_builtins:
            # Re-register built-in verticals to prevent test pollution
            from victor.core.verticals import _register_builtin_verticals

            _register_builtin_verticals()

    @classmethod
    def discover_external_verticals(cls) -> Dict[str, Type[VerticalBase]]:
        """Discover and register external verticals from entry points.

        Scans installed packages for the legacy ``victor.verticals`` entry point
        group and registers any valid vertical classes found. New external
        packages should publish ``VictorPlugin`` objects through
        ``victor.plugins`` instead. Legacy raw entry points must:
        - Inherit from the SDK VerticalBase protocol
        - Have a non-empty 'name' attribute

        Returns:
            Dictionary of newly discovered vertical names to their classes.

        Example legacy entry point in external package's pyproject.toml:
            [project.entry-points."victor.verticals"]
            security = "victor_security:SecurityAssistant"

        This would load SecurityAssistant from the victor_security package
        and register it if it's a valid vertical class.
        """
        import logging

        logger = logging.getLogger(__name__)
        discovered: Dict[str, Type[VerticalBase]] = {}

        # Avoid re-discovery on repeated calls
        if cls._external_discovered:
            return discovered

        # Direct entry point scan
        from victor.framework.entry_point_registry import get_entry_point_registry

        registry = get_entry_point_registry()
        group_obj = registry.get_group(cls.ENTRY_POINT_GROUP)

        eps = list(group_obj.entry_points.values()) if group_obj else []
        if eps:
            cls._warn_legacy_entry_point_usage(ep.name for ep, _loaded in eps)

        for ep, loaded in eps:
            try:
                # Load the entry point (imports the module and gets the object)
                # Entry point may already be loaded from the registry
                if loaded is not False:
                    vertical_class = loaded
                else:
                    vertical_class = ep.load()

                # Validate that it's a proper VerticalBase subclass
                if not cls._validate_external_vertical(vertical_class, ep.name):
                    continue

                # Check for name conflicts with existing verticals
                if vertical_class.name in cls._registry:
                    existing = cls._registry[vertical_class.name]
                    logger.warning(
                        f"External vertical '{ep.name}' has name '{vertical_class.name}' "
                        f"which conflicts with existing vertical {existing.__name__}. "
                        f"Skipping registration."
                    )
                    continue

                # Register the vertical
                cls.register(vertical_class)
                discovered[vertical_class.name] = vertical_class
                logger.info(
                    f"Discovered external vertical: {vertical_class.name} " f"(from {ep.value})"
                )

            except Exception as e:
                # Log the error but continue with other entry points
                logger.warning(
                    f"Failed to load external vertical '{ep.name}' from "
                    f"entry point '{ep.value}': {e}"
                )
                continue

        cls._external_discovered = True

        if discovered:
            logger.info(
                f"Discovered {len(discovered)} external vertical(s): "
                f"{', '.join(discovered.keys())}"
            )

        return discovered

    @classmethod
    def _warn_legacy_entry_point_usage(cls, entry_names: Iterable[str]) -> None:
        """Emit a one-time deprecation warning for raw ``victor.verticals`` usage."""

        if cls._legacy_entry_point_warning_emitted:
            return

        names = ", ".join(sorted(entry_names))
        message = (
            "Legacy raw vertical entry points via 'victor.verticals' are deprecated. "
            "Publish VictorPlugin objects via 'victor.plugins' instead. "
            f"Observed legacy entries: {names}"
        )
        logger.warning(message)
        cls._legacy_entry_point_warning_emitted = True

    @classmethod
    def _validate_external_vertical(
        cls,
        vertical_class: Any,
        entry_point_name: str,
    ) -> bool:
        """Validate that an external vertical class is properly implemented.

        Args:
            vertical_class: The class loaded from the entry point.
            entry_point_name: Name of the entry point (for error messages).

        Returns:
            True if the vertical is valid, False otherwise.
        """
        import logging

        logger = logging.getLogger(__name__)

        # Check if it's a class
        if not isinstance(vertical_class, type):
            logger.warning(
                f"External vertical '{entry_point_name}' is not a class "
                f"(got {type(vertical_class).__name__}). Skipping."
            )
            return False

        # Check if it inherits from the SDK protocol base.
        # Runtime VerticalBase subclasses satisfy this automatically.
        if not issubclass(vertical_class, SdkVerticalBase):
            logger.warning(
                f"External vertical '{entry_point_name}' ({vertical_class.__name__}) "
                f"does not inherit from VerticalBase. Skipping."
            )
            return False

        # Validate the minimal callable contract without executing runtime-heavy hooks.
        required_methods = (
            "get_name",
            "get_description",
            "get_tools",
            "get_system_prompt",
        )
        for method_name in required_methods:
            method = getattr(vertical_class, method_name, None)
            if method is None or not callable(method):
                logger.warning(
                    "External vertical '%s' (%s) is missing required method '%s'. Skipping.",
                    entry_point_name,
                    vertical_class.__name__,
                    method_name,
                )
                return False

        raw_api_version = getattr(vertical_class, "VERTICAL_API_VERSION", None)
        if raw_api_version is None:
            logger.warning(
                "External vertical '%s' (%s) has no VERTICAL_API_VERSION; defaulting to 1.",
                entry_point_name,
                vertical_class.__name__,
            )

        manifest = get_or_create_vertical_manifest(vertical_class)
        if manifest is None:
            logger.warning(
                "External vertical '%s' (%s) has no valid manifest metadata. Skipping.",
                entry_point_name,
                vertical_class.__name__,
            )
            return False

        if not manifest.name:
            logger.warning(
                "External vertical '%s' (%s) has no manifest name defined. Skipping.",
                entry_point_name,
                vertical_class.__name__,
            )
            return False

        # Check API version compatibility
        api_version = int(getattr(manifest, "api_version", 0) or 0)
        if api_version < cls.MINIMUM_SUPPORTED_API_VERSION:
            logger.error(
                f"External vertical '{entry_point_name}' ({vertical_class.__name__}) "
                f"API version {api_version} is below minimum supported "
                f"version {cls.MINIMUM_SUPPORTED_API_VERSION}. Skipping."
            )
            return False
        if api_version > cls.CURRENT_API_VERSION:
            logger.error(
                f"External vertical '{entry_point_name}' ({vertical_class.__name__}) "
                f"API version {api_version} is newer than current "
                f"version {cls.CURRENT_API_VERSION}. Skipping."
            )
            return False

        return True

    @classmethod
    def reset_discovery(cls) -> None:
        """Reset the external discovery flag (for testing).

        This allows discover_external_verticals() to run again and clears both
        the legacy ``victor.verticals`` cache path and the canonical
        ``victor.plugins`` cache path used by runtime loading.
        """
        cls._external_discovered = False
        cls._legacy_entry_point_warning_emitted = False
        try:
            from victor.core.verticals.vertical_loader import get_vertical_loader

            get_vertical_loader().reset_discovery_state()
        except Exception:
            pass

        try:
            from victor.framework.module_loader import get_entry_point_cache

            get_entry_point_cache().invalidate(cls.ENTRY_POINT_GROUP)
            get_entry_point_cache().invalidate("victor.plugins")
        except Exception:
            pass

        try:
            from victor.framework.entry_point_loader import (
                clear_entry_point_loader_cache,
            )

            clear_entry_point_loader_cache()
        except Exception:
            pass

        try:
            from victor.core.tool_dependency_loader import (
                clear_tool_dependency_entry_point_cache,
                clear_vertical_tool_dependency_provider_cache,
            )

            clear_tool_dependency_entry_point_cache()
            clear_vertical_tool_dependency_provider_cache()
        except Exception:
            pass
